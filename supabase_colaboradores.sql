-- PESQUISA ANÔNIMA DE ALIMENTAÇÃO DOS COLABORADORES - CABANA CLUBE
-- Executar no Supabase > SQL Editor. Não altera as tabelas das pesquisas de clientes.
create table if not exists public.colaboradores_pesquisa_respostas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  answers jsonb not null
);
alter table public.colaboradores_pesquisa_respostas enable row level security;
drop policy if exists "anon_insert_colaboradores_pesquisa" on public.colaboradores_pesquisa_respostas;
drop policy if exists "auth_select_colaboradores_pesquisa" on public.colaboradores_pesquisa_respostas;
create policy "anon_insert_colaboradores_pesquisa"
on public.colaboradores_pesquisa_respostas for insert to anon
with check (jsonb_typeof(answers) = 'object' and octet_length(answers::text) <= 4000);
create policy "auth_select_colaboradores_pesquisa"
on public.colaboradores_pesquisa_respostas for select to authenticated using (true);
grant insert on public.colaboradores_pesquisa_respostas to anon;
grant select on public.colaboradores_pesquisa_respostas to authenticated;
grant usage, select on sequence public.colaboradores_pesquisa_respostas_id_seq to anon, authenticated;