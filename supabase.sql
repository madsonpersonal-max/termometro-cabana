-- PESQUISA DE SATISFAÇÃO - RESTAURANTE CABANA CLUBE
-- Execute este script no Supabase > SQL Editor.
-- A tabela antiga termometro_respostas será preservada; esta pesquisa usa tabela separada.
create table if not exists public.restaurante_pesquisa_respostas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  respondent_type text,
  answers jsonb not null
);
alter table public.restaurante_pesquisa_respostas enable row level security;
drop policy if exists "anon_insert_restaurante_pesquisa" on public.restaurante_pesquisa_respostas;
drop policy if exists "auth_select_restaurante_pesquisa" on public.restaurante_pesquisa_respostas;
create policy "anon_insert_restaurante_pesquisa"
on public.restaurante_pesquisa_respostas for insert to anon
with check (jsonb_typeof(answers) = 'object' and octet_length(answers::text) <= 12000);
create policy "auth_select_restaurante_pesquisa"
on public.restaurante_pesquisa_respostas for select to authenticated using (true);
grant insert on public.restaurante_pesquisa_respostas to anon;
grant select on public.restaurante_pesquisa_respostas to authenticated;
grant usage, select on sequence public.restaurante_pesquisa_respostas_id_seq to anon, authenticated;
